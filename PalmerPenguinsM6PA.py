# Import required modules
import math

# Constants representing the species and count
SP_CHINSTRAP = "Chinstrap"
SP_GENTOO = "Gentoo"
SP_ADELIE = "Adelie"

NUM_CHINSTRAP = 68
NUM_GENTOO = 123
NUM_ADELIE = 151

# User defined functions
def calculate_percentage(count, total):
  """This function is used to calculate the penguin species percentages."""
  return count / total * 100

def classify_species(percent):
  """This function is used to calculate the penguin species size."""
  if percent < 25:
    return "small"
  elif (percent >= 25) and (percent < 40):
    return "medium"
  else:
    return "large"

def get_position_description(
    selected_species,
    largest_species,
    smallest_species
):
  """This function determines species relative size position among groups."""
  if selected_species == largest_species:
    return "largest"
  elif selected_species == smallest_species:
    return "smallest"
  else:
    return "middle-sized"

def display_species_statistics(names, counts, percentages):
  """This function displays species statistics."""
  for index, species in enumerate(names):
    print(f"{species}: {counts[index]} {percentages[index]:.2f}%")
  print()

# Main function
def main():

  # Lists containing related penguin data
  species_names = [
      SP_CHINSTRAP,
      SP_GENTOO,
      SP_ADELIE
  ]
  species_counts = [
      NUM_CHINSTRAP,
      NUM_GENTOO,
      NUM_ADELIE
  ]

  # Determine largest and smallest species group
  largest_count = max(species_counts)
  smallest_count = min(species_counts)
  largest_index = species_counts.index(largest_count)
  smallest_index = species_counts.index(smallest_count)
  largest_species = species_names[largest_index]
  smallest_species = species_names[smallest_index]

  # Calculate dataset statistics
  total_species = len(species_names)
  total_penguins = sum(species_counts)

  average_penguins = total_penguins / total_species
  average_penguins_rounded_up = math.ceil(average_penguins)

  # Get species percentages with function call
  chinstrap_percent = \
    calculate_percentage(species_counts[0], total_penguins)
  gentoo_percent = \
    calculate_percentage(species_counts[1], total_penguins)
  adelie_percent = \
    calculate_percentage(species_counts[2], total_penguins)

  # List of species percentages
  species_percentages = [
      chinstrap_percent,
      gentoo_percent,
      adelie_percent
  ]

  # Output the species names with introductory text and formatted statistics
  print("Introducing the Palmer Penguins:")
  print()
  print("\t" f"{species_names[0]}!")
  print("\t" f"{species_names[1]}!")
  print("and last but not least...")
  print()
  print("\t" f"{species_names[2]}!")
  print()
  print(f"There are a total of {total_species} penguin species in this "
    f"dataset.")
  print(f"There are a total of {total_penguins} penguins in the dataset.")
  print(f"The average number of penguins per species is "
    f"{average_penguins:.1f}.")
  print(f"The average rounded up is {average_penguins_rounded_up}.")
  print()

  # Display the species statistics with function call
  display_species_statistics(species_names, \
                           species_counts, species_percentages)

  # Introductory text continued.
  print(f"The species with the most observations is {largest_species} with "
    f"{largest_count} penguins.")
  print(f"The species with the fewest observations is {smallest_species} with "
    f"{smallest_count} penguins.")

  # Creating and initalizing variable for valid species selection
  valid_selections = 0

  # Prompt the user to select a species
  print()
  print("Explore a species:")
  print()
  species_choice = input("Enter Chinstrap, Gentoo, Adelie, or Done: ")

  # Species exploration with a while loop
  while species_choice != "Done":

    # Validate the species selection
    if species_choice not in species_names:
      print()
      print(f"{species_choice} is not one of the species in this dataset.")
      print()

    # Determine the selected species
    else:
      if species_choice == species_names[0]:
        selected_index = 0
      elif species_choice == species_names[1]:
        selected_index = 1
      else:
        selected_index = 2
      # Count number of valid selections
      valid_selections += 1

      # Retrieve the selected species data
      selected_species = species_names[selected_index]
      selected_count = species_counts[selected_index]
      selected_percent = species_percentages[selected_index]

      # Classify the species by its percentage with function call
      size_category = classify_species(selected_percent)

      # Determine the species relative position with function call
      position_descripton = \
        get_position_description(selected_species, \
                                largest_species, smallest_species)

      # Compare the selected count to the average
      average_position = \
        "above" if selected_count > average_penguins else "below"

    # Display the selected species statistics
    if species_choice in species_names:
      print()
      print(f"{selected_species} has {selected_count} observations, "
        f"representing {selected_percent:.2f}% of the dataset.")
      print(f"{selected_species} is classified as a {size_category} species "
        f"group.")
      print(f"{selected_species} is the {position_descripton} species group.")
      print(f"Its observation count is {average_position} the dataset average "
        f"of {average_penguins:.1f}.")
      print()
    species_choice = input("Enter Chinstrap, Gentoo, Adelie, or Done: ")

  # Display final summary
  print()
  print(f"You explored {valid_selections} valid species.")
  print("Exploration complete.")

# Call the main function to start the program
main()